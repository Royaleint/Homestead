function VendorIdentity:BuildIndexes()
    self.ByMapID = {}
    self.ByExpansion = {}
    local function indexVendor(npcID, vendor)
        vendor.npcID = npcID
        if vendor.mapID then
            self.ByMapID[vendor.mapID] = self.ByMapID[vendor.mapID] or {}
            table.insert(self.ByMapID[vendor.mapID], npcID)
        end
        if vendor.expansion then
            self.ByExpansion[vendor.expansion] = self.ByExpansion[vendor.expansion] or {}
            table.insert(self.ByExpansion[vendor.expansion], npcID)
        end
    end
    for npcID, vendor in pairs(self.Vendors) do
        indexVendor(npcID, vendor)
    end
    -- Staged additions (Data/VendorStagedAdditions.lua, pipeline-owned) join
    -- the indexes unless a baseline row already owns the npcID.
    for npcID, vendor in pairs(self.StagedAdditions or {}) do
        if not self.Vendors[npcID] then
            indexVendor(npcID, vendor)
        end
    end
end

function VendorIdentity:GetVendor(npcID)
    local canonicalID = self.Aliases and self.Aliases[npcID]
    return self.Vendors[npcID]
        or (canonicalID and self.Vendors[canonicalID])
        or (self.StagedAdditions and self.StagedAdditions[npcID])
        or nil
end

function VendorIdentity:HasVendor(npcID)
    return self:GetVendor(npcID) ~= nil
end

function VendorIdentity:GetAllVendors()
    local vendors = {}
    for _, vendor in pairs(self.Vendors) do
        vendors[#vendors + 1] = vendor
    end
    for npcID, vendor in pairs(self.StagedAdditions or {}) do
        if not self.Vendors[npcID] then
            vendors[#vendors + 1] = vendor
        end
    end
    return vendors
end

function VendorIdentity:InvalidateVendorCache()
    self:BuildIndexes()
end

function VendorIdentity:GetVendorsByMapID(mapID)
    if not self.ByMapID then self:BuildIndexes() end
    local npcIDs = self.ByMapID and self.ByMapID[mapID]
    if not npcIDs then return {} end
    local result = {}
    for _, npcID in ipairs(npcIDs) do
        -- HS-217: BuildIndexes indexes StagedAdditions-only vendors into
        -- ByMapID too, but this lookup was checking self.Vendors alone —
        -- staged-only vendors indexed fine and then dropped silently here.
        -- Mirrors GetVendor's fallback exactly.
        local vendor = self.Vendors[npcID] or (self.StagedAdditions and self.StagedAdditions[npcID])
        if vendor then result[#result + 1] = vendor end
    end
    return result
end

function VendorIdentity:GetVendorsByExpansion(expansion)
    if not self.ByExpansion then self:BuildIndexes() end
    local npcIDs = self.ByExpansion and self.ByExpansion[expansion]
    if not npcIDs then return {} end
    local result = {}
    for _, npcID in ipairs(npcIDs) do
        -- HS-217: same StagedAdditions fallback as GetVendorsByMapID above.
        local vendor = self.Vendors[npcID] or (self.StagedAdditions and self.StagedAdditions[npcID])
        if vendor then result[#result + 1] = vendor end
    end
    return result
end

function VendorIdentity:GetVendorCount()
    local count = 0
    for _ in pairs(self.Vendors) do count = count + 1 end
    return count
end

function VendorIdentity:GetAliasCount()
    local count = 0
    for _ in pairs(self.Aliases or {}) do count = count + 1 end
    return count
end

